class DialogueVoice:
    def __init__(self, character_id: Callable[[], str]):
        self.character_id = character_id
        self._turns: dict[tuple[str, str], int] = defaultdict(int)

    @property
    def name(self) -> str:
        return profile(self.character_id()).name

    def error(self, message: str, detail: str | None = None) -> str:
        if self.character_id() == "moru":
            return message
        if detail is not None:
            return self.render("error", details=detail)
        heading, separator, detail = message.partition("\n")
        if detail.startswith("기본 모드에서는"):
            detail = (
                "\n".join(detail.splitlines()[1:-1]) + "\n한 번에 한 명령. 변경은 확인 후 적용."
            )
        body = ERRORS.get(heading, heading) + (separator + detail if detail else "")
        return self.render("error", details=body)

    def render(self, event: str, *, details: str = "", moru_text: str = "") -> str:
        character_id = profile(self.character_id()).id
        if character_id == "moru":
            return moru_text or details
        event = event if event in PHRASES else "info"
        key = (character_id, event)
        turn = self._turns[key]
        self._turns[key] += 1
        variants = PHRASES[event][("chiikawa", "hachiware", "usagi").index(character_id)]
        speech = variants[turn % len(variants)]
        content = speech + ("\n" + details if details else "")
        if character_id == "usagi":
            calls = USAGI_CALLS.get(event, ("우라!", "푸루야!", "우라라라!!"))
            return f"{calls[turn % len(calls)]} ({content})"
        return content


